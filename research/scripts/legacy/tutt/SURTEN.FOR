        SUBROUTINE SURTEN(P,E,OMEGA,Q)
C...
C...POUR CALCULER LE COEFFICIENT DE SURTENSION DU SYSTEME, CONNAISSANT
C...LA PUISSANCE DISSIPEE P, L' ENERGIE STOCKEE E, ET LA PULSATION
C...OMEGA.
        Q=OMEGA*E/P
        WRITE(6,1) Q
1       FORMAT(' COEFFICIENT DE SURTENSION =',F12.4)
        RETURN
        END

