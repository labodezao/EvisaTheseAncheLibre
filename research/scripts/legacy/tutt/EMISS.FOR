        SUBROUTINE EMISS(Q,OMEGA,GA,GB,ESTOCA,SEMI)
C...
C...POUR CALCULER L' ENERGIE ESTOCA REELLEMENT STOCKEE DANS LE
C...SYSTEME, AINSI QUE LE CRITERE DE SATISFACTION SEMI DISANT SI
C...L' AUTO ENTRETIEN AURA LIEU FACILEMENT.
C...Q, OMEGA, GA, GB SONT EN ENTREE.
C...
C...LA PUISSANCE GENEREE PAR L' AUTO ENTRETIEN EST UNE FONCTION
C...DE L' ENERGIE STOCKEE DANS LE RESONATEUR: P=F(E) OU F EST
C...PARAMETRISEE COMME F(E)=GA*E - GB*E**2. (LA PUISSANCE GENEREE
C...EST UNE FONCTION D' ABORD CROISSANTE DE L' ENERGIE STOCKEE, 
C...PUIS DECROISSANTE CAR LE MECANISME D' AUTO ENTRETIEN A UNE 
C...EFFICACITE MAXIMALE POUR UNE CERTAINE AMPLITUDE DANS LE TUYAU.)
C...
C...LE COEFFICIENT DE SURTENSION DU SYSTEME EST DEFINI COMME 
C...Q=OMEGA*E/P. C' EST UNE GRANDEUR CARACTERISTIQUE DU SYSTEME, 
C...CALCULEE DANS ESTOCK. L' ENERGIE EFFECTIVEMENT STOCKEE DANS LE
C...SYSTEME S' OBTIENT EN RESOLVANT L' EQUATION Q=OMEGA*E/F(E), 
C...DONT LA SOLUTION EST ESTOCA=GA/GB-OMEGA/(GB*Q).
C...ENCORE FAUT-IL ESTOCA>0: SI Q EST TROP PETIT, L' AUTO ENTRETIEN
C...NE PEUT AVOIR LIEU.
C...
C...ON PRENDRA SEMI=ESTOCA COMME CRITERE DE SATISFACTION (GRAND
C...QUAND ON EST CONTENT, 0 QUAND L' AUTO ENTRETIEN NE PEUT AVOIR
C...LIEU).
C...
        ESTOCA=(GA/GB)-(OMEGA/(GB*Q))
        IF(ESTOCA.LT.0.) GO TO 1
        GO TO 3
1       WRITE(6,2)
        WRITE(8,2)
2       FORMAT(' ATTENTION, L AUTO ENTRETIEN NE PEUT AVOIR LIEU!')
        ESTOCA=0.
3       SEMI=ESTOCA
        RETURN
        END

