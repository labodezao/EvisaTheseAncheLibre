        SUBROUTINE TIMBRE(OMEGA,OTAB,NTAB,STIM)
C...
C...POUR CALCULER UN CRITERE DE SATISFACTION DISANT SI LA NOTE QU'
C...ON CONSIDERE AURA UN TIMBRE RICHE, IE CORRESPOND A UN MINIMUM 
C...D' IMPEDANCE POUR TOUS LES MULTIPLES DE LA FREQUENCE OMEGA
C...DETERMINEE PAR PROXI COMME ETANT LA FREQUENCE DE RESONANCE DU
C...SYSTEME.
C...LES TROIS PREMIERS ARGUMENTS SONT EN ENTREE.
C...
        DIMENSION OTAB(1)
        STIM=0.
        IMAX=10
        OMAX=OTAB(NTAB)
C...BOUCLE SUR L' HARMONIQUE N0 I DE OMEGA.
        DO 1 I=2,IMAX
        OREF=FLOAT(I)*OMEGA
        IF(OREF.GT.OMAX) GO TO 2
        CALL PROXI(OREF,OTAB,NTAB,NTUBE,CENTS,SJUS,OTUBE)
C... POUR SAVOIR QUEL EST LE ZERO DE ZIM LE PLUS PROCHE DE OREF.
C...OTUBE EST CE ZERO, ET SJUS EST L' ECART RELATIF (OTUBE-OREF)/OREF
        STIM=STIM+ABS(SJUS)
1       CONTINUE
C...NORMALISATION DE STIM PAR LE NOMBRE NH=I-1 D' HARMONIQUES QU' ON
C...A EU A EXAMINER.
2       CONTINUE
        NH=I-1
        STIM=STIM/FLOAT(NH)
C...ON EST CONTENT QUAND STIM EST PETIT.
        RETURN
        END

