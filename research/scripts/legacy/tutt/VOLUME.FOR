        SUBROUTINE VOLUME(PUITOT,ESTOCN,ESTOCA,PCR,PRAYA,SVOL)
C...
C...POUR CALCULER LA PUISSANCE RAYONNEE PRAYA, AINSI QU' UN CRITERE
C...DE SATISFACTION DISANT QUEL EST LE RENDEMENT SONORE DU SYSTEME
C...POUR LA NOTE QU' ON CONSIDERE.
C...LES TROIS PREMIERS ARGUMENTS SONT EN ENTREE.
C...
C...ON A UNE ENERGIE ESTOCK STOCKEE DANS LE SYSTEME. CETTE QUANTITE
C...EST FIXEE EN PRINCIPE A LA VALEUR ESTOCA PAR LE MECANISME D' AUTO
C...ENTRETIEN. (ESTOCA EST CALCULE PAR EMISS). LE MECANISME ETANT MAL
C...CONNU, ESTOCK N' EST PAS CALCULE PAR LTRANS EN VALEUR ABSOLUE, 
C...MAIS EN VALEUR RELATIVE, EN SUPPOSANT ARBITRAIREMENT LA PRESSION
C...FIXEE A 1 QUELQUE PART DANS LE TUBE. CE CALCUL PRELIMINAIRE DONNE
C...LES QUANTITES ESTOCN ET PRAYN, POUR L' ENERGIE STOCKEE ET LA
C...PUISSANCE RAYONNEE RESPECTIVEMENT. LA PUISSANCE RAYONNEE REELLEMENT
C...PRAYA VAUT PRAYA = ESTOCA*PRAYN/ESTOCN.
C...
        PUITTA =ESTOCA*PUITOT/ESTOCN
C...PUITTA EST LA PUISSANCE TOTALE EN VALEUR ABSOLUE
        PRAYA=PUITTA*PCR
C...PCR EST LA PROPORTION DE LA PUISSANCE TOTALE QUI EST RAYONNEE
        SVOL=PRAYA
C...LE CRITERE DE SATISFACTION SVOL EST ELEVE QUAND ON EST CONTENT.
        RETURN
        END

