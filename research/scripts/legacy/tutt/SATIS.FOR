        SUBROUTINE SATIS(SJUS,STIM,SVOL,SEMI,SLIB,CJUS,CTIM,
     SCVOL,CEMI,CLIB,PRAISO,ERAISO,SCRIT)
C...
C...POUR CALCULER UN CRITERE DE SATISFACTION GLOBAL SCRIT, 
C...CONNAISSANT LES CRITERES PARTIELS S... ET LEURS COEFFICIENTS
C...C... SEUL LE DERNIER ARGUMENT EST EN SORTIE.
C...
C...RAPPEL DE LA SIGNIFICATION PHYSIQUE DES GRANDEURS S... :
C...SJUS=(OMEGA-OREF)/OREF CONCERNE LA JUSTESSE
C...STIM=MOYENNE DES SJUS POUR LES PARTIELS ;STIM CONCERNE LA
C...RICHESSE DU TIMBRE.
C...SVOL=PRAYA, PUISSANCE REELLEMENT RAYONNEE; SVOL CONCERNE
C...LE VOLUME SONORE.
C...SEMI=ESTOCA, ENERGIE REELLEMENT STOCKEE DANS LE TUYAU; SEMI
C...CONCERNE L' EMISSION ET L' AUTOENTRETIEN.
C...SLIB=DELTAOMEGA/OMEGA POUR DES VARIATIONS RAISONNABLES DES
C...PARAMETRES DE L' EMBOUCHURE. SLIB CONCERNE LE CHAMP DE 
C...LIBERTE EN FREQUENCES.
C...
C...ON FABRIQUE A PARTIR DES GRANDEURS PHYSIQUES S... UNE NOTE 
C...DE SATISFACTION COMPRISE ENTRE 0 ET 1 :
C...     SATISF= FONCTION (S...)
C...0=SATISFACTION MINIMALE; 1=SATISFACTION MAXIMALE.
C...ON PONDERE ENSUITE PAR LES COEFFICIENTS C... POUR CALCULER
C...LE CRITERE DE SATISFACTION GLOBAL (LUI AUSSI ENTRE 0 ET 1)
C...
C...JUSTESSE ET TIMBRE: LA FONCTION DE SATISFACTION EST GAUSSIENNE
C...AVEC UNE LARGEUR A MI HAUTEUR DE 2/10E DE TON.
        DELTA=1.2E-2
        SATJUS=EXP(-SJUS**2/DELTA**2)
        SATSTM=EXP(-STIM**2/DELTA**2)
C...VOLUME
C...PRAISO EST LA PUISSANCE RAYONNEE CORRESPONDANT A UNE 
C...SATISFACTION MOYENNE.
        SVRAIS=PRAISO/0.6
        SATVOL=TANH(SVOL/SVRAIS)
C...EMISSION
C...ERAISO EST L' ENERGIE STOCKEE CORRESPONDANT A UNE
C...SATISFACTION MOYENNE.
        SERAIS=ERAISO/0.6
        SATEMI=TANH(SEMI/SERAIS)
C...LIBERTE: LA FONCTION DE SATISFACTION A UN OPTIMUM POUR UNE
C...LIBERTE DE 1/2 TON
        SLIB0=3.E-2
        VAUXI=SLIB/SLIB0
        SATLIB=2.*VAUXI/(1.+VAUXI**2)
C...
C...PONDERATION ET CALCUL DU CRITERE DE SATISFACTION GLOBAL
        SOMCOE=CJUS+CTIM+CVOL+CEMI+CLIB
        TOTAL=CJUS*SATJUS+CTIM*SATSTM+CVOL*SATVOL+CEMI*SATEMI
     S+CLIB*SATLIB
        SCRIT=TOTAL/SOMCOE
        RETURN
        END

